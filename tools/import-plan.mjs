// Turns a description of clients and their projects (and, optionally, a development plan exported
// from a claude.ai artifact's database, one JSON file per task) into SQL for the portal database.
// Project details stay out of this repository: keep the config and the SQL it prints elsewhere,
// and run the SQL against D1.
//
//   node tools/import-plan.mjs projects.json > projects.sql
//
// projects.json:
// {
//   "clients": [{ "id": "jpn", "name": "Jesus People Network" }],
//   "plans": [{
//     "id": "jpn-mvp", "client": "jpn", "title": "...", "summary": "...", "status": "active",
//     "tasks_dir": "/path/to/export/tasks",                      (optional)
//     "phases": [{ "key": "sp1-site", "title": "Stopping Point 1: Public site" }],
//     "scope": [{ "title": "...", "detail": "..." }],              (optional: what's included)
//     "terms": "...",                                               (optional)
//     "payments": [{ "label": "...", "amount": 3000, "due_date": null, "paid": false }]   (optional)
//   }]
// }
// A single plan object at the top level (the older format) also works.
// Each task file holds { title, group, order, completed, completedDate } (directly or under "data").
// Re-running updates the same clients, plans, phases, tasks, scope and payments (ids are derived
// from the plan id) and keeps chat, comments, members and paid marks already in the portal.
// Agreements are imported as drafts; share them from the portal when ready.
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const input = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const config = input.plans ? input : { clients: [], plans: [input] };
const q = v => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const now = new Date().toISOString();
const toIso = d => (d ? new Date(`${d} 12:00 UTC`).toISOString() : null);
const cents = v => Math.round(Number(v) * 100);

const lines = ['-- Generated by tools/import-plan.mjs'];
let taskTotal = 0;

for (const c of config.clients || []) {
  lines.push(`INSERT INTO clients (id, name, notes, created_at, updated_at) VALUES (${q(c.id)}, ${q(c.name)}, ${q(c.notes || '')}, ${q(now)}, ${q(now)})`,
    `  ON CONFLICT (id) DO UPDATE SET name = excluded.name, updated_at = excluded.updated_at;`);
}

for (const plan of config.plans) {
  const status = plan.status || 'active';
  lines.push(
    `INSERT INTO plans (id, client_id, title, summary, status, listed, terms, created_at, updated_at) VALUES (${q(plan.id)}, ${q(plan.client || null)}, ${q(plan.title)}, ${q(plan.summary || '')}, ${q(status)}, 0, ${q(plan.terms || '')}, ${q(now)}, ${q(now)})`,
    `  ON CONFLICT (id) DO UPDATE SET client_id = excluded.client_id, title = excluded.title, summary = excluded.summary, status = excluded.status, terms = excluded.terms, updated_at = excluded.updated_at;`,
  );
  (plan.phases || []).forEach((p, i) => {
    lines.push(`INSERT INTO phases (id, plan_id, title, position) VALUES (${q(`${plan.id}:${p.key}`)}, ${q(plan.id)}, ${q(p.title)}, ${i + 1})`,
      `  ON CONFLICT (id) DO UPDATE SET title = excluded.title, position = excluded.position;`);
  });
  const tasks = plan.tasks_dir
    ? readdirSync(plan.tasks_dir).filter(f => f.endsWith('.json')).map(f => {
      const raw = JSON.parse(readFileSync(join(plan.tasks_dir, f), 'utf8'));
      return { key: f.replace(/\.json$/, ''), ...(raw.data || raw) };
    }).sort((a, b) => (a.order ?? 0) - (b.order ?? 0))
    : [];
  for (const t of tasks) {
    const phase = (plan.phases || []).find(p => p.key === t.group);
    if (!phase) throw new Error(`Task ${t.key} is in group "${t.group}", which has no phase in the config`);
    const done = t.completed === true;
    const doneAt = done ? toIso(t.completedDate) || now : null;
    lines.push(
      `INSERT INTO tasks (id, plan_id, phase_id, title, status, position, done_at, created_at, updated_at) VALUES (${q(`${plan.id}:${t.key}`)}, ${q(plan.id)}, ${q(`${plan.id}:${phase.key}`)}, ${q(t.title)}, ${q(done ? 'done' : 'todo')}, ${t.order ?? 0}, ${q(doneAt)}, ${q(now)}, ${q(doneAt || now)})`,
      `  ON CONFLICT (id) DO UPDATE SET phase_id = excluded.phase_id, title = excluded.title, status = excluded.status, position = excluded.position, done_at = excluded.done_at, updated_at = excluded.updated_at;`,
    );
  }
  taskTotal += tasks.length;
  (plan.scope || []).forEach((s, i) => {
    lines.push(`INSERT INTO scope_items (id, plan_id, title, detail, position, created_at) VALUES (${q(`${plan.id}:scope${i + 1}`)}, ${q(plan.id)}, ${q(s.title)}, ${q(s.detail || '')}, ${i + 1}, ${q(now)})`,
      `  ON CONFLICT (id) DO UPDATE SET title = excluded.title, detail = excluded.detail, position = excluded.position;`);
  });
  (plan.payments || []).forEach((p, i) => {
    lines.push(`INSERT INTO payments (id, plan_id, label, amount_cents, due_date, paid_at, position, created_at) VALUES (${q(`${plan.id}:pay${i + 1}`)}, ${q(plan.id)}, ${q(p.label)}, ${cents(p.amount)}, ${q(p.due_date || null)}, ${q(p.paid ? toIso(p.paid_date) || now : null)}, ${i + 1}, ${q(now)})`,
      `  ON CONFLICT (id) DO UPDATE SET label = excluded.label, amount_cents = excluded.amount_cents, due_date = excluded.due_date, position = excluded.position;`);
  });
  lines.push(`INSERT INTO activity (plan_id, actor_type, actor_name, action, ref_type, ref_id, summary, created_at) VALUES (${q(plan.id)}, 'system', 'Import', 'plan_imported', 'plan', ${q(plan.id)}, ${q(`Imported ${plan.title}${tasks.length ? ` with ${tasks.length} tasks` : ''}`)}, ${q(now)});`);
  console.error(`${plan.title}: ${tasks.length} tasks, ${(plan.scope || []).length} included items, ${(plan.payments || []).length} payments (${status}).`);
}
console.log(lines.join('\n'));
console.error(`${config.clients?.length || 0} clients, ${config.plans.length} plans, ${taskTotal} tasks.`);
