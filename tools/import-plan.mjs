// Turns a development plan exported from a claude.ai artifact's database (one JSON file per task)
// into SQL for the portal database. The plan's contents stay out of this repository: point the
// script at the export folder and run the SQL it prints against D1.
//
//   node tools/import-plan.mjs plan.json > plan.sql
//
// plan.json:
// {
//   "id": "jpn-mvp", "title": "...", "summary": "...",
//   "tasks_dir": "/path/to/export/tasks",
//   "phases": [{ "key": "sp1-site", "title": "Stopping Point 1: Public site" }, ...]
// }
// Each task file holds { title, group, order, completed, completedDate } (directly or under "data").
// Re-running replaces the same plan, phases and tasks (ids are derived from the plan id), and keeps
// any chat, comments and members already in the portal.
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const config = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const q = v => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const now = new Date().toISOString();
const toIso = d => (d ? new Date(`${d} 12:00 UTC`).toISOString() : null);

const tasks = readdirSync(config.tasks_dir).filter(f => f.endsWith('.json')).map(f => {
  const raw = JSON.parse(readFileSync(join(config.tasks_dir, f), 'utf8'));
  return { key: f.replace(/\.json$/, ''), ...(raw.data || raw) };
}).sort((a, b) => (a.order ?? 0) - (b.order ?? 0));

const lines = [
  '-- Generated by tools/import-plan.mjs',
  `INSERT INTO plans (id, title, summary, status, listed, created_at, updated_at) VALUES (${q(config.id)}, ${q(config.title)}, ${q(config.summary || '')}, 'active', 0, ${q(now)}, ${q(now)})`,
  `  ON CONFLICT (id) DO UPDATE SET title = excluded.title, summary = excluded.summary, updated_at = excluded.updated_at;`,
];
config.phases.forEach((p, i) => {
  lines.push(`INSERT INTO phases (id, plan_id, title, position) VALUES (${q(`${config.id}:${p.key}`)}, ${q(config.id)}, ${q(p.title)}, ${i + 1})`,
    `  ON CONFLICT (id) DO UPDATE SET title = excluded.title, position = excluded.position;`);
});
for (const t of tasks) {
  const phase = config.phases.find(p => p.key === t.group);
  if (!phase) throw new Error(`Task ${t.key} is in group "${t.group}", which has no phase in the config`);
  const done = t.completed === true;
  const doneAt = done ? toIso(t.completedDate) || now : null;
  lines.push(
    `INSERT INTO tasks (id, plan_id, phase_id, title, status, position, done_at, created_at, updated_at) VALUES (${q(`${config.id}:${t.key}`)}, ${q(config.id)}, ${q(`${config.id}:${phase.key}`)}, ${q(t.title)}, ${q(done ? 'done' : 'todo')}, ${t.order ?? 0}, ${q(doneAt)}, ${q(now)}, ${q(doneAt || now)})`,
    `  ON CONFLICT (id) DO UPDATE SET phase_id = excluded.phase_id, title = excluded.title, status = excluded.status, position = excluded.position, done_at = excluded.done_at, updated_at = excluded.updated_at;`,
  );
}
lines.push(`INSERT INTO activity (plan_id, actor_type, actor_name, action, ref_type, ref_id, summary, created_at) VALUES (${q(config.id)}, 'system', 'Import', 'plan_imported', 'plan', ${q(config.id)}, ${q(`Imported ${tasks.length} tasks into ${config.title}`)}, ${q(now)});`);
console.log(lines.join('\n'));
console.error(`${tasks.length} tasks in ${config.phases.length} phases (${tasks.filter(t => t.completed).length} done).`);
